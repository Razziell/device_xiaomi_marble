#include <algorithm>
#include <cerrno>
#include <chrono>
#include <climits>
#include <cstdio>
#include <fcntl.h>
#include <poll.h>
#include <pthread.h>
#include <signal.h>
#include <string_view>
#include <sys/socket.h>
#include <sys/stat.h>
#include <unistd.h>

namespace marble::power {

// No helper thread and no F_SETFL on the caller's shared open-file description.
// Ordinary Binder dumps use a pipe. Sockets use per-call MSG_DONTWAIT; regular
// files/devices are rejected because O_NONBLOCK does not bound their writes.
inline bool writeBoundedDump(int fd, std::string_view text) {
    constexpr size_t kMaxBytes = 16 * 1024;
    constexpr auto kBudget = std::chrono::milliseconds(100);
    if (text.size() > kMaxBytes) { errno = EOVERFLOW; return false; }
    const int flags = fcntl(fd, F_GETFL);
    if (flags < 0) return false;
    if ((flags & O_ACCMODE) == O_RDONLY) { errno = EBADF; return false; }
    struct stat st {};
    if (fstat(fd, &st) != 0) return false;
    const bool socket = S_ISSOCK(st.st_mode);
    int pipeFd = -1;
    if (!socket) {
        if (!S_ISFIFO(st.st_mode)) { errno = EOPNOTSUPP; return false; }
        // Reopening a pipe through procfs creates an independent description.
        // dup() would share O_NONBLOCK with the caller and other writers.
        char path[64];
        std::snprintf(path, sizeof(path), "/proc/self/fd/%d", fd);
        pipeFd = open(path, O_WRONLY | O_NONBLOCK | O_CLOEXEC);
        if (pipeFd < 0) return false; // Fail closed if procfs/SELinux denies it.
        struct stat reopened {};
        if (fstat(pipeFd, &reopened) != 0 || !S_ISFIFO(reopened.st_mode) ||
            reopened.st_dev != st.st_dev || reopened.st_ino != st.st_ino) {
            close(pipeFd);
            errno = EBADF;
            return false;
        }
    }
    struct CloseFd {
        int fd;
        ~CloseFd() { if (fd >= 0) close(fd); }
    } closePipe{pipeFd};

    // write() to a closed pipe must not kill the service. Block SIGPIPE only
    // on this thread and consume only a signal generated by our own EPIPE.
    sigset_t pipeSignal, oldMask, pending;
    sigemptyset(&pipeSignal);
    sigaddset(&pipeSignal, SIGPIPE);
    const int error = pthread_sigmask(SIG_BLOCK, &pipeSignal, &oldMask);
    if (error != 0) { errno = error; return false; }
    const bool alreadyPending = sigpending(&pending) != 0 || sigismember(&pending, SIGPIPE) == 1;
    struct RestoreMask {
        const sigset_t& mask;
        ~RestoreMask() { pthread_sigmask(SIG_SETMASK, &mask, nullptr); }
    } restoreMask{oldMask};

    const int target = socket ? fd : pipeFd;
    const auto deadline = std::chrono::steady_clock::now() + kBudget;
    size_t written = 0;
    while (written < text.size()) {
        if (std::chrono::steady_clock::now() >= deadline) {
            errno = ETIMEDOUT;
            return false;
        }
        const size_t chunk = std::min(text.size() - written, size_t{PIPE_BUF});
        const ssize_t count = socket
                ? send(target, text.data() + written, chunk, MSG_DONTWAIT | MSG_NOSIGNAL)
                : write(target, text.data() + written, chunk);
        if (count > 0) { written += static_cast<size_t>(count); continue; }
        if (count == 0) { errno = EIO; return false; }
        if (errno == EPIPE && !socket && !alreadyPending) {
            const timespec noWait{0, 0};
            while (sigtimedwait(&pipeSignal, nullptr, &noWait) < 0 && errno == EINTR) {}
            errno = EPIPE;
            return false;
        }
        if (errno == EINTR) continue;
        if (errno != EAGAIN && errno != EWOULDBLOCK) return false;
        const auto remaining = std::chrono::ceil<std::chrono::milliseconds>(
                deadline - std::chrono::steady_clock::now());
        if (remaining.count() <= 0) { errno = ETIMEDOUT; return false; }
        pollfd ready{target, POLLOUT, 0};
        const int result = poll(&ready, 1, static_cast<int>(remaining.count()));
        if (result == 0) { errno = ETIMEDOUT; return false; }
        if (result < 0 && errno != EINTR) return false;
        if (result > 0 && (ready.revents & (POLLERR | POLLHUP | POLLNVAL))) {
            errno = EPIPE;
            return false;
        }
    }
    return true;
}

}  // namespace marble::power
