#pragma once

#include <algorithm>
#include <cerrno>
#include <chrono>
#include <climits>
#include <fcntl.h>
#include <poll.h>
#include <pthread.h>
#include <signal.h>
#include <string_view>
#include <sys/socket.h>
#include <unistd.h>

namespace marble::power {

// No helper thread and no F_SETFL on the caller's shared open-file description.
// The descriptor is used as received: SELinux grants the HAL only fd:use and
// fifo_file:write on a dumpstate pipe, so fstat() (getattr) and reopening it
// through procfs (open) are denied there and must not be required.
// Sockets use per-call MSG_DONTWAIT. A pipe is written only after poll()
// reports room, in chunks of at most PIPE_BUF: a pipe that is not full has a
// free page, so such a write does not sleep while this is the only writer.
// Seekable descriptors (regular files, most devices) are rejected because
// poll() does not bound their writes.
inline bool writeBoundedDump(int fd, std::string_view text) {
    constexpr size_t kMaxBytes = 16 * 1024;
    constexpr auto kBudget = std::chrono::milliseconds(100);
    if (text.size() > kMaxBytes) { errno = EOVERFLOW; return false; }
    const int flags = fcntl(fd, F_GETFL);
    if (flags < 0) return false;
    if ((flags & O_ACCMODE) == O_RDONLY) { errno = EBADF; return false; }
    if (lseek(fd, 0, SEEK_CUR) != static_cast<off_t>(-1)) { errno = EOPNOTSUPP; return false; }
    if (errno != ESPIPE) return false;

    // write() to a closed pipe must not kill the service. Block SIGPIPE only
    // on this thread and consume only a signal generated by our own EPIPE.
    sigset_t pipeSignal, oldMask, pending;
    sigemptyset(&pipeSignal);
    sigaddset(&pipeSignal, SIGPIPE);
    const int error = pthread_sigmask(SIG_BLOCK, &pipeSignal, &oldMask);
    if (error != 0) { errno = error; return false; }
    const bool alreadyPending = sigpending(&pending) != 0 || sigismember(&pending, SIGPIPE) == 1;
    struct RestoreMask {
        const sigset_t& mask;
        ~RestoreMask() { pthread_sigmask(SIG_SETMASK, &mask, nullptr); }
    } restoreMask{oldMask};

    const auto deadline = std::chrono::steady_clock::now() + kBudget;
    const auto waitWritable = [&] {
        for (;;) {
            const auto remaining = std::chrono::ceil<std::chrono::milliseconds>(
                    deadline - std::chrono::steady_clock::now());
            if (remaining.count() <= 0) { errno = ETIMEDOUT; return false; }
            pollfd ready{fd, POLLOUT, 0};
            const int result = poll(&ready, 1, static_cast<int>(remaining.count()));
            if (result == 0) { errno = ETIMEDOUT; return false; }
            if (result < 0) {
                if (errno == EINTR) continue;
                return false;
            }
            // A pipe without readers reports POLLERR: fail before write() so
            // no SIGPIPE is generated at all in the common closed-reader case.
            if (ready.revents & (POLLERR | POLLNVAL)) { errno = EPIPE; return false; }
            if (ready.revents & POLLOUT) return true;
            errno = EPIPE;
            return false;
        }
    };

    // The first send() tells sockets from pipes (ENOTSOCK) without fstat().
    bool socket = true;
    size_t written = 0;
    while (written < text.size()) {
        if (std::chrono::steady_clock::now() >= deadline) {
            errno = ETIMEDOUT;
            return false;
        }
        const size_t chunk = std::min(text.size() - written, size_t{PIPE_BUF});
        ssize_t count;
        if (socket) {
            count = send(fd, text.data() + written, chunk, MSG_DONTWAIT | MSG_NOSIGNAL);
            if (count < 0 && errno == ENOTSOCK) {
                socket = false;
                continue;
            }
        } else {
            if (!waitWritable()) return false;
            count = write(fd, text.data() + written, chunk);
        }
        if (count > 0) { written += static_cast<size_t>(count); continue; }
        if (count == 0) { errno = EIO; return false; }
        if (errno == EINTR) continue;
        if (errno == EPIPE) {
            // The reader went away between poll() and write().
            if (!socket && !alreadyPending) {
                const timespec noWait{0, 0};
                while (sigtimedwait(&pipeSignal, nullptr, &noWait) < 0 && errno == EINTR) {}
            }
            errno = EPIPE;
            return false;
        }
        if (errno != EAGAIN && errno != EWOULDBLOCK) return false;
        // Pipes poll at the top of the loop; a full socket waits here.
        if (socket && !waitWritable()) return false;
    }
    return true;
}

}  // namespace marble::power
